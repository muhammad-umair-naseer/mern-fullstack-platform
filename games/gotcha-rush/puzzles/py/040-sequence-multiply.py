# @title Multiplying sequences
# @difficulty 1
# @tags strings, lists, operators
# @distractor ababab 7 [0, 0, 0]
# @distractor 6 34 [0, 0, 0]
# @distractor ababab 34 [0, 3]
# @explain * on a sequence repeats it, and + on strings concatenates, so "3" + "4" is "34" rather than 7.
print("ab" * 3, "3" + "4", [0] * 3)
