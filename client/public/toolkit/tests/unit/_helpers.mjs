import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { execSync, execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const FX = join(ROOT, 'tests', 'fixtures');
export const OUT = join(ROOT, 'tests', 'unit', 'out');
mkdirSync(OUT, { recursive: true });
export const fixture = (name) => new Uint8Array(readFileSync(join(FX, name)));
export const save = (name, bytes) => { const p = join(OUT, name); writeFileSync(p, bytes); return p; };
export const has = (cmd) => { try { execSync(`command -v ${cmd}`, { stdio: 'ignore' }); return true; } catch { return false; } };
export const sh = (cmd) => execSync(cmd, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
export const shFile = (cmd, args) => execFileSync(cmd, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
export const qpdfCheck = (p) => { if (!has('qpdf')) return true; sh(`qpdf --check "${p}"`); return true; };
export const pdfText = (p) => (has('pdftotext') ? sh(`pdftotext "${p}" -`) : null);
