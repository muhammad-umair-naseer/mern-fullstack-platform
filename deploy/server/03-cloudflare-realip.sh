#!/usr/bin/env bash
# Run on the server with sudo. Writes /etc/nginx/conf.d/cloudflare-realip.conf
# from Cloudflare's published IP ranges, so Nginx (and the app's rate limits)
# see each visitor's real IP instead of Cloudflare's. Only requests that come
# FROM a Cloudflare address may set it, so nobody else can fake an IP.
# Safe to re-run; 04-nginx-site.sh installs a weekly cron to refresh it.
#
#   sudo bash deploy/server/03-cloudflare-realip.sh
set -euo pipefail
[ "$(id -u)" -eq 0 ] || { echo "Run with sudo."; exit 1; }

OUT=/etc/nginx/conf.d/cloudflare-realip.conf
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

{
  echo "# Generated by deploy/server/03-cloudflare-realip.sh on $(date -u +%F). Do not edit."
  for list in ips-v4 ips-v6; do
    curl -fsS "https://www.cloudflare.com/$list" | while read -r cidr; do
      [ -n "$cidr" ] && echo "set_real_ip_from $cidr;"
    done
  done
  echo "real_ip_header CF-Connecting-IP;"
} > "$TMP"

# Refuse to install a list that came back empty (network hiccup).
grep -q "set_real_ip_from" "$TMP" || { echo "Could not fetch Cloudflare IP ranges; keeping the old file."; exit 1; }

if ! cmp -s "$TMP" "$OUT"; then
  install -m 644 "$TMP" "$OUT"
  if nginx -t; then systemctl reload nginx; echo "Updated $OUT"; else echo "nginx -t failed"; exit 1; fi
else
  echo "Already up to date."
fi
